use crate::{NodeId, SourceMap};

/// Preserve source links for unsupported XML instead of silently losing it.
pub(super) fn nodes(map: &SourceMap) -> Vec<NodeId> {
    const TYPED: &[&str] = &[
        "device",
        "vendor",
        "vendorID",
        "name",
        "series",
        "version",
        "description",
        "licenseText",
        "cpu",
        "revision",
        "endian",
        "mpuPresent",
        "fpuPresent",
        "fpuDP",
        "dspPresent",
        "icachePresent",
        "dcachePresent",
        "itcmPresent",
        "dtcmPresent",
        "vtorPresent",
        "nvicPrioBits",
        "vendorSystickConfig",
        "deviceNumInterrupts",
        "sauNumRegions",
        "sauRegionsConfig",
        "region",
        "base",
        "limit",
        "access",
        "headerSystemFilename",
        "headerDefinitionsPrefix",
        "addressUnitBits",
        "width",
        "size",
        "protection",
        "resetValue",
        "resetMask",
        "peripherals",
        "peripheral",
        "displayName",
        "alternatePeripheral",
        "groupName",
        "prependToName",
        "appendToName",
        "headerStructName",
        "baseAddress",
        "addressBlock",
        "offset",
        "usage",
        "interrupt",
        "value",
        "registers",
        "register",
        "cluster",
        "alternateCluster",
        "alternateGroup",
        "alternateRegister",
        "addressOffset",
        "dataType",
        "modifiedWriteValues",
        "writeConstraint",
        "writeAsRead",
        "useEnumeratedValues",
        "range",
        "minimum",
        "maximum",
        "readAction",
        "fields",
        "field",
        "bitRange",
        "bitOffset",
        "bitWidth",
        "lsb",
        "msb",
        "enumeratedValues",
        "enumeratedValue",
        "isDefault",
        "dim",
        "dimIncrement",
        "dimIndex",
        "dimName",
        "dimArrayIndex",
        "headerEnumName",
    ];
    (0..map.node_count())
        .filter_map(|i| {
            let id = NodeId(u32::try_from(i).ok()?);
            let node = map.node(id)?;
            (!TYPED.contains(&node.name.as_ref())).then_some(id)
        })
        .collect()
}
